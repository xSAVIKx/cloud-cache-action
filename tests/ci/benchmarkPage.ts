/**
 * Writes the website's benchmark page from the artifacts of one Transfer benchmark run.
 *
 *   gh run download <run-id> --dir <dir>
 *   node tests/ci/benchmarkPage.ts <dir> [docs/guide/benchmarks.md]
 *
 * Reads every `benchmark-<provider>/benchmark-results.json` under <dir>. Each table compares the
 * defaults, the fastest fixed configuration and `transfer-tuning: auto` for one size and one
 * direction, with one column per provider.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';

const MiB = 1024 * 1024;

interface Sample {
  kind: 'save' | 'restore';
  config: string;
  inputs: Record<string, string>;
  bytes: number;
  transferMs: number[];
}

interface Results {
  label: string;
  provider: string;
  matrix: string;
  repeats: number;
  runner: string;
  runId: string;
  date: string;
  runs: Array<{ sizeMb: number; archiveBytes: number; samples: Sample[] }>;
}

const median = (values: number[]): number => {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
};

const rate = (s: Sample): number => s.bytes / MiB / (median(s.transferMs) / 1000);
/** The rate as the table prints it, so that the bold rule compares what the reader sees. */
const shown = (s: Sample): number => Math.round(rate(s));
/** A streaming restore also extracts, so its rate is not a transfer rate like the others. */
const isFixedTransfer = (s: Sample): boolean =>
  s.config !== 'auto' && s.inputs.streaming !== 'true';

function readResults(dir: string): Results[] {
  return fs
    .readdirSync(dir)
    .filter((name) => name.startsWith('benchmark-') && name !== 'benchmark-compression')
    .map((name) => path.join(dir, name, 'benchmark-results.json'))
    .filter((file) => fs.existsSync(file))
    .map((file) => JSON.parse(fs.readFileSync(file, 'utf8')) as Results)
    .sort((a, b) => a.label.localeCompare(b.label));
}

const count = (n: number, noun: string): string => `${n} ${noun}${n === 1 ? '' : 's'}`;

function sizeLabel(sizeMb: number): string {
  return sizeMb >= 1024 ? `${sizeMb / 1024} GiB` : `${sizeMb} MiB`;
}

/** One table: rows are configurations, columns are providers, cells are MiB/s. */
function table(results: Results[], sizeMb: number, kind: 'save' | 'restore'): string[] {
  const samplesOf = (r: Results): Sample[] =>
    r.runs.find((run) => run.sizeMb === sizeMb)?.samples.filter((s) => s.kind === kind) ?? [];
  const configs = [...new Set(results.flatMap((r) => samplesOf(r).map((s) => s.config)))];
  const lines = [
    `| ${kind === 'save' ? 'Upload' : 'Download'} | ${results.map((r) => r.label).join(' | ')} |`,
    `| --- | ${results.map(() => '---:').join(' | ')} |`,
  ];
  for (const config of configs) {
    const cells = results.map((r) => {
      const samples = samplesOf(r);
      const sample = samples.find((s) => s.config === config);
      if (sample === undefined) {
        return '–';
      }
      const fixed = samples.filter(isFixedTransfer).map(shown);
      const value = shown(sample);
      const bold =
        fixed.length > 0 && value >= Math.max(...fixed) && sample.inputs.streaming !== 'true';
      return bold ? `**${value}**` : String(value);
    });
    const name = config === 'auto' ? '`transfer-tuning: auto`' : config;
    lines.push(`| ${name} | ${cells.join(' | ')} |`);
  }
  return lines;
}

/** Auto against the defaults, as a ratio of the transfer rates, per provider and size. */
function summary(results: Results[], sizes: number[], kind: 'save' | 'restore'): string[] {
  const lines = [
    `| ${kind === 'save' ? 'Save' : 'Restore'} | ${results.map((r) => r.label).join(' | ')} |`,
    `| --- | ${results.map(() => '---:').join(' | ')} |`,
  ];
  for (const sizeMb of sizes) {
    const cells = results.map((r) => {
      const samples =
        r.runs.find((run) => run.sizeMb === sizeMb)?.samples.filter((s) => s.kind === kind) ?? [];
      const auto = samples.find((s) => s.config === 'auto');
      const defaults = samples.find((s) => s.config.startsWith('defaults'));
      return auto && defaults ? `${(rate(auto) / rate(defaults)).toFixed(2)}×` : '–';
    });
    lines.push(`| ${sizeLabel(sizeMb)} | ${cells.join(' | ')} |`);
  }
  return lines;
}

function page(results: Results[], fittedTo: string | undefined): string {
  const first = results[0];
  const sizes = [...new Set(results.flatMap((r) => r.runs.map((run) => run.sizeMb)))].sort(
    (a, b) => a - b
  );
  const runUrl = `https://github.com/xSAVIKx/cloud-cache-action/actions/runs/${first.runId}`;
  const out = [
    '---',
    'title: Benchmarks',
    'description: "Measured restore and save times of Cloud Cache Action for each storage provider, cache size and transfer setting, from the Transfer benchmark workflow."',
    '---',
    '',
    '<!-- Generated by tests/ci/benchmarkPage.ts. Edit the generator, not this file. -->',
    '',
    '# Benchmarks',
    '',
    'This page compares the default transfer settings, other fixed settings and',
    `\`transfer-tuning: auto\` on ${count(results.length, 'provider')} and ${count(sizes.length, 'cache size')}. See`,
    '[Performance](./performance.md) for what the settings do and how to select them.',
    '',
    '## How the numbers were measured',
    '',
    `- Run [${first.runId}](${runUrl}) of the Transfer benchmark workflow, on ${first.date}.`,
    `- Runner: \`ubuntu-latest\`, ${first.runner}.`,
    `- Each configuration ran ${first.repeats} times. The tables show the median transfer rate in MiB/s.`,
    '- The payload is random bytes, so the archive is about as large as the payload.',
    '- The transfer rate is the S3 transfer alone. It does not include tar, compression or the sha256 check.',
    '- **Bold** is the fastest fixed configuration in that column, and the `auto` row when it is',
    '  as fast or faster.',
    ...(fittedTo === undefined || fittedTo === first.runId
      ? []
      : [
          '- The `auto` rules come from an earlier sweep, run',
          `  [${fittedTo}](https://github.com/xSAVIKx/cloud-cache-action/actions/runs/${fittedTo}). This`,
          '  page uses a different run, so the `auto` rows are not the data the rules were fitted to.',
        ]),
    '- The jobs for the three providers ran at the same time. The numbers depend on the region, the',
    '  runner and the time of day. The same configuration can change by more than 30% between',
    '  runs. Compare rows inside one table, not numbers between runs.',
    '',
    '## `transfer-tuning: auto` against the defaults',
    '',
    'A value above 1 means that `auto` was faster than the defaults.',
    '',
    ...summary(results, sizes, 'restore'),
    '',
    ...summary(results, sizes, 'save'),
    '',
  ];
  for (const sizeMb of sizes) {
    out.push(`## ${sizeLabel(sizeMb)} cache`, '');
    out.push('### Restore', '', ...table(results, sizeMb, 'restore'), '');
    out.push('### Save', '', ...table(results, sizeMb, 'save'), '');
  }
  out.push(
    '## Run the benchmark yourself',
    '',
    '```sh',
    'gh workflow run benchmark.yml -f size-mb=128,512,2048 -f matrix=sweep -f repeats=2',
    `gh run download <run-id> --dir bench`,
    'node tests/ci/benchmarkPage.ts bench docs/guide/benchmarks.md [rules-run-id]',
    '```',
    ''
  );
  return out.join('\n');
}

const [dir, target = 'docs/guide/benchmarks.md', fittedTo] = process.argv.slice(2);
if (dir === undefined) {
  throw new Error(
    'Usage: node tests/ci/benchmarkPage.ts <artifact dir> [target] [run id the auto rules come from]'
  );
}
const results = readResults(dir);
if (results.length === 0) {
  throw new Error(`No benchmark-*/benchmark-results.json under ${dir}`);
}
const runIds = new Set(results.map((r) => r.runId));
if (runIds.size > 1) {
  throw new Error(`The artifacts come from more than one run: ${[...runIds].join(', ')}`);
}
fs.writeFileSync(target, page(results, fittedTo));
console.log(`Wrote ${target} from ${results.length} provider(s)`);
