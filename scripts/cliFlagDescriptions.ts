// Writes src/cli/flagDescriptions.ts from the `description:` fields of the action manifests.
// The CLI help prints these texts, so the flag help and the action inputs stay in step.
// Run: node scripts/cliFlagDescriptions.ts. tests/contract/cliHelp.test.ts fails when the
// committed file differs from the manifests.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

type Command = 'restore' | 'save' | 'inspect' | 'prune';

/**
 * The manifest of each command. It is the same manifest that src/cli/defaults.ts takes the input
 * defaults from, so the CLI has the inputs, the defaults and the descriptions of one manifest.
 */
export const DESCRIPTION_SOURCES: Record<Command, string> = {
  restore: 'action.yml',
  save: 'action.yml',
  inspect: 'inspect/action.yml',
  prune: 'prune/action.yml',
};

/** A description shorter than this gets its next sentence too. */
const MIN_LENGTH = 30;

/**
 * The first sentence of a manifest description, or more sentences until the text has at least
 * MIN_LENGTH characters. The help prints the default and the env var on its own.
 */
export function shortDescription(description: string): string {
  const text = description.replace(/\s+/g, ' ').trim();
  const sentences = text.split(/(?<=\.)\s+(?=[A-Z0-9])/);
  let result = '';
  for (const sentence of sentences) {
    result = result === '' ? sentence : `${result} ${sentence}`;
    if (result.length >= MIN_LENGTH) {
      break;
    }
  }
  return result;
}

/** The short description of each input of each command. */
export function buildFlagDescriptions(root: string): Record<Command, Record<string, string>> {
  const result = {} as Record<Command, Record<string, string>>;
  for (const [command, file] of Object.entries(DESCRIPTION_SOURCES) as Array<[Command, string]>) {
    const manifest = parse(readFileSync(path.join(root, file), 'utf8')) as {
      inputs: Record<string, { description?: unknown }>;
    };
    const table: Record<string, string> = {};
    for (const [name, spec] of Object.entries(manifest.inputs)) {
      const description = typeof spec.description === 'string' ? spec.description : '';
      if (description !== '') {
        table[name] = shortDescription(description);
      }
    }
    result[command] = table;
  }
  return result;
}

function render(data: Record<Command, Record<string, string>>): string {
  return [
    '// Generated by scripts/cliFlagDescriptions.ts from the action manifests. Do not edit.',
    "import type { CliCommand } from './defaults';",
    '',
    '/** The short description of each input, from the `description:` field of its manifest. */',
    `export const FLAG_DESCRIPTIONS: Record<CliCommand, Record<string, string>> = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');
}

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(ROOT, 'src', 'cli', 'flagDescriptions.ts');
  writeFileSync(out, render(buildFlagDescriptions(ROOT)));
  execFileSync(path.join(ROOT, 'node_modules', '.bin', 'biome'), ['format', '--write', out], {
    stdio: 'inherit',
  });
}
